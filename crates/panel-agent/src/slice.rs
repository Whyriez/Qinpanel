//! Systemd slice configuration manager for tenant resource limits.
//!
//! Handles generation and removal of drop-in files for `panel-u<uid>.slice`:
//! Path: `/etc/systemd/system/panel-u<uid>.slice.d/50-limits.conf`
//! Manages: `MemoryMax`, `MemoryHigh`, `CPUQuota`, `TasksMax`, `IOWeight`.

use crate::AgentError;
use crate::system::SystemRunner;
use panel_core::tenant::TenantUid;
use panel_proto::{
    SliceAppliedResponse, SliceApplyRequest, SliceRemoveRequest, SliceRemovedResponse,
};
use std::path::{Path, PathBuf};
use std::sync::Arc;
use tracing::info;

pub const DEFAULT_SYSTEMD_SYSTEM_DIR: &str = "/etc/systemd/system";

pub struct SliceManager {
    runner: Arc<dyn SystemRunner>,
    base_dir: PathBuf,
}

impl SliceManager {
    pub fn new(runner: Arc<dyn SystemRunner>) -> Self {
        Self {
            runner,
            base_dir: PathBuf::from(DEFAULT_SYSTEMD_SYSTEM_DIR),
        }
    }

    pub fn with_base_dir(runner: Arc<dyn SystemRunner>, base_dir: impl AsRef<Path>) -> Self {
        Self {
            runner,
            base_dir: base_dir.as_ref().to_path_buf(),
        }
    }

    /// Generates slice name for a given tenant UID, e.g. "panel-u10001.slice".
    pub fn slice_name(uid: u32) -> String {
        format!("panel-u{uid}.slice")
    }

    /// Returns drop-in directory for slice, e.g. "/etc/systemd/system/panel-u10001.slice.d".
    pub fn dropin_dir(&self, uid: u32) -> PathBuf {
        self.base_dir.join(format!("{}.d", Self::slice_name(uid)))
    }

    /// Returns drop-in configuration file path, e.g. ".../50-limits.conf".
    pub fn dropin_conf_path(&self, uid: u32) -> PathBuf {
        self.dropin_dir(uid).join("50-limits.conf")
    }

    /// Validates limit inputs before writing them to systemd slice configs.
    fn validate_limits(req: &SliceApplyRequest) -> Result<(), AgentError> {
        if req
            .memory_max
            .as_deref()
            .is_some_and(|m| m.chars().any(|c| !c.is_ascii_alphanumeric()))
        {
            return Err(AgentError::InvalidInput(format!(
                "Invalid characters in memory_max: {:?}",
                req.memory_max
            )));
        }
        if req
            .memory_high
            .as_deref()
            .is_some_and(|m| m.chars().any(|c| !c.is_ascii_alphanumeric()))
        {
            return Err(AgentError::InvalidInput(format!(
                "Invalid characters in memory_high: {:?}",
                req.memory_high
            )));
        }
        if req
            .cpu_quota
            .as_deref()
            .is_some_and(|c| c.chars().any(|ch| !ch.is_ascii_digit() && ch != '%'))
        {
            return Err(AgentError::InvalidInput(format!(
                "Invalid characters in cpu_quota: {:?}",
                req.cpu_quota
            )));
        }
        if req.io_weight.is_some_and(|io| !(1..=10000).contains(&io)) {
            return Err(AgentError::InvalidInput(format!(
                "IOWeight must be between 1 and 10000, got {:?}",
                req.io_weight
            )));
        }
        Ok(())
    }

    /// Applies cgroup v2 resource limits to tenant slice via systemd drop-in.
    pub fn apply_slice(&self, req: SliceApplyRequest) -> Result<SliceAppliedResponse, AgentError> {
        let tenant_uid =
            TenantUid::parse(req.uid).map_err(|e| AgentError::InvalidInput(e.to_string()))?;
        let uid = tenant_uid.as_u32();

        Self::validate_limits(&req)?;

        let slice_name = Self::slice_name(uid);
        let dropin_dir = self.dropin_dir(uid);
        let conf_path = self.dropin_conf_path(uid);

        // Build 50-limits.conf content
        let mut content = String::new();
        content.push_str("# Generated by QonPanel agent. Do not edit manually.\n");
        content.push_str("[Slice]\n");

        if let Some(ref mem) = req.memory_max {
            content.push_str(&format!("MemoryMax={mem}\n"));
        }
        if let Some(ref mem_high) = req.memory_high {
            content.push_str(&format!("MemoryHigh={mem_high}\n"));
        }
        if let Some(ref cpu) = req.cpu_quota {
            let val = if cpu.ends_with('%') {
                cpu.clone()
            } else {
                format!("{cpu}%")
            };
            content.push_str(&format!("CPUQuota={val}\n"));
        }
        if let Some(tasks) = req.tasks_max {
            content.push_str(&format!("TasksMax={tasks}\n"));
        }
        if let Some(io) = req.io_weight {
            content.push_str(&format!("IOWeight={io}\n"));
        }

        // Create drop-in directory if missing (root-owned 0755)
        self.runner.create_dir_all(&dropin_dir, 0o755, 0, 0)?;

        // Write drop-in file (0644 root:root)
        self.runner
            .write_file(&conf_path, content.as_bytes(), 0o644)?;

        // Reload systemd configuration
        self.runner.run_command("systemctl", &["daemon-reload"])?;

        info!(
            "Applied slice resource limits for tenant UID {} to {}",
            uid,
            conf_path.display()
        );

        Ok(SliceAppliedResponse {
            uid,
            slice_name,
            dropin_path: conf_path.to_string_lossy().to_string(),
        })
    }

    /// Removes tenant slice drop-in configuration and reloads systemd.
    pub fn remove_slice(
        &self,
        req: SliceRemoveRequest,
    ) -> Result<SliceRemovedResponse, AgentError> {
        let tenant_uid =
            TenantUid::parse(req.uid).map_err(|e| AgentError::InvalidInput(e.to_string()))?;
        let uid = tenant_uid.as_u32();

        let slice_name = Self::slice_name(uid);
        let dropin_dir = self.dropin_dir(uid);
        let conf_path = self.dropin_conf_path(uid);

        // Remove drop-in file if present
        self.runner.remove_file(&conf_path)?;

        // Remove drop-in directory
        self.runner.remove_dir_all(&dropin_dir)?;

        // Reload systemd configuration
        self.runner.run_command("systemctl", &["daemon-reload"])?;

        info!("Removed slice resource limits for tenant UID {}", uid);

        Ok(SliceRemovedResponse { uid, slice_name })
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used)]
mod tests {
    use super::*;
    use crate::system::{MockAction, MockSystemRunner};

    #[test]
    fn test_apply_and_remove_slice() {
        let runner = Arc::new(MockSystemRunner::new());
        let manager = SliceManager::with_base_dir(
            Arc::clone(&runner) as Arc<dyn SystemRunner>,
            "/tmp/systemd",
        );

        let apply_req = SliceApplyRequest {
            uid: 10001,
            memory_max: Some("512M".to_string()),
            memory_high: Some("400M".to_string()),
            cpu_quota: Some("100%".to_string()),
            tasks_max: Some(150),
            io_weight: Some(200),
        };

        let applied = manager
            .apply_slice(apply_req)
            .expect("apply slice succeeds");
        assert_eq!(applied.uid, 10001);
        assert_eq!(applied.slice_name, "panel-u10001.slice");

        let actions = runner.recorded_actions();

        // Verify WriteFile action occurred
        let written = actions.iter().find_map(|a| match a {
            MockAction::WriteFile {
                path,
                content,
                mode,
            } => Some((
                path.clone(),
                String::from_utf8_lossy(content).to_string(),
                *mode,
            )),
            _ => None,
        });

        assert!(written.is_some());
        let (path, content, mode) = written.unwrap();
        assert!(path.ends_with("panel-u10001.slice.d/50-limits.conf"));
        assert_eq!(mode, 0o644);
        assert!(content.contains("[Slice]"));
        assert!(content.contains("MemoryMax=512M"));
        assert!(content.contains("MemoryHigh=400M"));
        assert!(content.contains("CPUQuota=100%"));
        assert!(content.contains("TasksMax=150"));
        assert!(content.contains("IOWeight=200"));

        // Verify daemon-reload was executed
        let reload = actions.iter().any(|a| match a {
            MockAction::Command { binary, args } => {
                binary == "systemctl" && args == &["daemon-reload"]
            }
            _ => false,
        });
        assert!(reload, "systemctl daemon-reload must be invoked");

        // Now test remove_slice
        let rem_req = SliceRemoveRequest { uid: 10001 };
        let removed = manager
            .remove_slice(rem_req)
            .expect("remove slice succeeds");
        assert_eq!(removed.uid, 10001);
        assert_eq!(removed.slice_name, "panel-u10001.slice");

        let actions_after = runner.recorded_actions();
        let file_removed = actions_after.iter().any(|a| match a {
            MockAction::RemoveFile { path } => {
                path.ends_with("panel-u10001.slice.d/50-limits.conf")
            }
            _ => false,
        });
        assert!(file_removed, "drop-in file must be removed");
    }

    #[test]
    fn test_invalid_uid_and_input_rejected() {
        let runner = Arc::new(MockSystemRunner::new());
        let manager = SliceManager::new(runner as Arc<dyn SystemRunner>);

        // UID outside tenant range
        let res = manager.apply_slice(SliceApplyRequest {
            uid: 999, // Root/system UID
            memory_max: Some("512M".to_string()),
            memory_high: None,
            cpu_quota: None,
            tasks_max: None,
            io_weight: None,
        });
        assert!(res.is_err());

        // Malicious characters in memory limit
        let res_inj = manager.apply_slice(SliceApplyRequest {
            uid: 10001,
            memory_max: Some("512M\n[Service]\nExecStart=/bin/bad".to_string()),
            memory_high: None,
            cpu_quota: None,
            tasks_max: None,
            io_weight: None,
        });
        assert!(res_inj.is_err());
    }
}
