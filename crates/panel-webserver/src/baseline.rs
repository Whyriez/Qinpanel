use crate::error::WebserverError;
use std::fs;
use std::path::{Path, PathBuf};

/// Baseline Nginx configuration generator and installer.
#[derive(Debug, Clone)]
pub struct NginxBaselineConfig {
    /// Base configuration directory (e.g. `/etc/panel/nginx`).
    pub base_dir: PathBuf,
    /// Central log directory (e.g. `/var/log/panel`).
    pub log_dir: PathBuf,
    /// ACME challenge root directory (e.g. `/var/lib/panel/acme`).
    pub acme_dir: PathBuf,
    /// Port of the internal panel-api daemon (default 7700).
    pub panel_api_port: u16,
    /// Public port for Qinpanel web interface (default 17890).
    pub panel_listen_port: u16,
    /// Number of worker processes (default "auto").
    pub worker_processes: String,
    /// Maximum simultaneous connections per worker (default 4096).
    pub worker_connections: u32,
    /// FastCGI cache directory (default `/var/cache/nginx/panel`).
    pub cache_dir: PathBuf,
}

impl Default for NginxBaselineConfig {
    fn default() -> Self {
        Self {
            base_dir: PathBuf::from("/etc/panel/nginx"),
            log_dir: PathBuf::from("/var/log/panel"),
            acme_dir: PathBuf::from("/var/lib/panel/acme"),
            cache_dir: PathBuf::from("/var/cache/nginx/panel"),
            panel_api_port: panel_core::production::INTERNAL_API_PORT,
            panel_listen_port: panel_core::production::PUBLIC_PANEL_PORT,
            worker_processes: "auto".to_string(),
            worker_connections: 4096,
        }
    }
}

impl NginxBaselineConfig {
    /// Creates a new configuration rooted at a specific base directory.
    pub fn new(base_dir: impl Into<PathBuf>) -> Self {
        let b = base_dir.into();
        Self {
            log_dir: b.join("logs"),
            acme_dir: b.join("acme"),
            cache_dir: b.join("cache"),
            base_dir: b,
            ..Default::default()
        }
    }

    /// Path to `snippets/` directory.
    pub fn snippets_dir(&self) -> PathBuf {
        self.base_dir.join("snippets")
    }

    /// Path to `conf.d/` directory.
    pub fn conf_d_dir(&self) -> PathBuf {
        self.base_dir.join("conf.d")
    }

    /// Path to `sites-available/` directory.
    pub fn sites_available_dir(&self) -> PathBuf {
        self.base_dir.join("sites-available")
    }

    /// Path to `sites-enabled/` directory.
    pub fn sites_enabled_dir(&self) -> PathBuf {
        self.base_dir.join("sites-enabled")
    }

    /// Path to main `nginx.conf`.
    pub fn nginx_conf_path(&self) -> PathBuf {
        self.base_dir.join("nginx.conf")
    }

    /// Generates the tuned main `nginx.conf`.
    pub fn render_nginx_conf(&self) -> String {
        let conf_d = self.conf_d_dir().to_string_lossy().replace('\\', "/");
        let sites_enabled = self
            .sites_enabled_dir()
            .to_string_lossy()
            .replace('\\', "/");
        let error_log = self
            .log_dir
            .join("error.log")
            .to_string_lossy()
            .replace('\\', "/");
        let access_log = self
            .log_dir
            .join("access.log")
            .to_string_lossy()
            .replace('\\', "/");

        format!(
            r#"# QonPanel Main Nginx Configuration (Tuned)
# Auto-generated by panel-webserver. Do not edit directly.

user www-data;
worker_processes {worker_processes};
worker_rlimit_nofile 65535;
pid /run/nginx.pid;

events {{
    worker_connections {worker_connections};
    multi_accept on;
    use epoll;
}}

http {{
    # Basic Settings
    sendfile on;
    tcp_nopush on;
    tcp_nodelay on;
    keepalive_timeout 65s;
    keepalive_requests 1000;
    types_hash_max_size 2048;
    server_tokens off;

    # Limits & Buffers
    client_max_body_size 100M;
    client_body_buffer_size 128k;
    client_header_buffer_size 1k;
    large_client_header_buffers 4 8k;

    # MIME Types
    include /etc/nginx/mime.types;
    default_type application/octet-stream;

    {log_format}

    access_log {access_log} panel_json;
    error_log {error_log} warn;

    # Gzip Compression
    gzip on;
    gzip_vary on;
    gzip_proxied any;
    gzip_comp_level 6;
    gzip_min_length 256;
    gzip_types
        text/plain
        text/css
        text/xml
        text/javascript
        application/json
        application/javascript
        application/x-javascript
        application/xml
        application/xml+rss
        image/svg+xml;

    # Include modular configurations
    include {conf_d}/*.conf;
    include {sites_enabled}/*.conf;
}}
"#,
            worker_processes = self.worker_processes,
            worker_connections = self.worker_connections,
            log_format = self.render_json_log_format(),
            access_log = access_log,
            error_log = error_log,
            conf_d = conf_d,
            sites_enabled = sites_enabled,
        )
    }

    /// Shared HTTP-context dependencies for panel vhosts. The distribution keeps
    /// ownership of nginx.conf, listeners and the panel's public-port proxy.
    pub fn render_host_http_conf(&self) -> String {
        let sites = self
            .sites_enabled_dir()
            .to_string_lossy()
            .replace('\\', "/");
        let conf_d = self.conf_d_dir().to_string_lossy().replace('\\', "/");
        format!(
            "# Managed by QonPanel: HTTP dependencies and tenant websites.\n\
             {}\n{}\n{}\ninclude {conf_d}/tuning*.conf;\ninclude {sites}/*.conf;\n",
            self.render_json_log_format(),
            self.render_websocket_conf(),
            self.render_fastcgi_cache_conf(),
        )
    }

    pub fn render_json_log_format(&self) -> &'static str {
        r#"log_format panel_json escape=json '{'
    '"time_local":"$time_iso8601",'
    '"remote_addr":"$remote_addr",'
    '"remote_user":"$remote_user",'
    '"request_method":"$request_method",'
    '"request_uri":"$request_uri",'
    '"status":$status,'
    '"body_bytes_sent":$body_bytes_sent,'
    '"request_time":$request_time,'
    '"http_referrer":"$http_referer",'
    '"http_user_agent":"$http_user_agent",'
    '"http_x_forwarded_for":"$http_x_forwarded_for",'
    '"host":"$host",'
    '"server_name":"$server_name",'
    '"upstream_addr":"$upstream_addr",'
    '"upstream_response_time":"$upstream_response_time",'
    '"upstream_status":"$upstream_status"'
'}';"#
    }

    /// Generates `conf.d/00-default.conf`: catch-all server rejecting unknown hosts with HTTP 444.
    pub fn render_default_catchall(&self) -> String {
        include_str!("../../../templates/nginx/nusa-reject-unknown.conf").to_owned()
    }

    /// Generates `conf.d/10-panel.conf`: vhost for the Qinpanel web interface.
    pub fn render_panel_vhost(&self) -> String {
        let security_headers = self
            .snippets_dir()
            .join("security-headers.conf")
            .to_string_lossy()
            .replace('\\', "/");

        format!(
            r#"# QonPanel Management Interface
# Proxies requests to internal unprivileged panel-api daemon.
# Only a connector on this server may supply Cloudflare visitor metadata.
map $remote_addr $qpanel_connector_visitor {{
    default "";
    127.0.0.1 $http_cf_visitor;
    ::1 $http_cf_visitor;
}}
map $http_host $qpanel_public_authority {{
    default $http_host;
    "" $host;
}}

server {{
    listen {port};
    listen [::]:{port};
    server_name _;

    client_max_body_size 100m;
    include {security_headers};

    # Reverse proxy to local panel-api daemon
    location / {{
        proxy_pass http://127.0.0.1:{api_port};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host $qpanel_public_authority;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Qpanel-Cf-Visitor $qpanel_connector_visitor;
        proxy_set_header CF-Visitor "";
        proxy_set_header X-Forwarded-Host "";
        proxy_set_header Forwarded "";
        proxy_read_timeout 86400s;
        proxy_send_timeout 86400s;
    }}
}}
"#,
            port = self.panel_listen_port,
            api_port = self.panel_api_port,
            security_headers = security_headers,
        )
    }

    /// Generates `conf.d/20-fastcgi-cache.conf`: Shared FastCGI microcache zone definition.
    pub fn render_fastcgi_cache_conf(&self) -> String {
        let cache_path = self.cache_dir.to_string_lossy().replace('\\', "/");
        format!(
            r#"# QonPanel FastCGI Microcache Configuration
# Shared keys zone and storage path across virtual hosts.
fastcgi_cache_path {cache_path} levels=1:2 keys_zone=panel_php_cache:10m max_size=250m inactive=60m use_temp_path=off;
fastcgi_cache_key "$scheme$request_method$host$request_uri";
"#,
            cache_path = cache_path
        )
    }

    /// Generates `conf.d/01-websocket.conf`: Connection upgrade mapping for WebSocket reverse proxying.
    pub fn render_websocket_conf(&self) -> String {
        r#"# WebSocket Connection Upgrade Mapping
# Auto-generated by panel-webserver. Do not edit directly.

map $http_upgrade $connection_upgrade {
    default upgrade;
    '' close;
}
"#
        .to_string()
    }

    /// Generates `snippets/acme.conf`: Let's Encrypt HTTP-01 challenge handler.
    pub fn render_acme_snippet(&self) -> String {
        let acme_path = self.acme_dir.to_string_lossy().replace('\\', "/");

        format!(
            r#"# ACME Challenge Handler (Let's Encrypt HTTP-01)
location ^~ /.well-known/acme-challenge/ {{
    default_type "text/plain";
    root {acme_path};
    allow all;
}}
"#,
            acme_path = acme_path
        )
    }

    /// Generates `snippets/security-headers.conf`: Recommended HTTP security headers.
    pub fn render_security_headers_snippet(&self) -> String {
        r#"# HTTP Security Headers (WCAG & OWASP Best Practices)
add_header X-Frame-Options "SAMEORIGIN" always;
add_header X-Content-Type-Options "nosniff" always;
add_header X-XSS-Protection "1; mode=block" always;
add_header Referrer-Policy "strict-origin-when-cross-origin" always;
"#
        .to_string()
    }

    /// Generates `snippets/deny-sensitive.conf`: Blocks hidden directories and sensitive file types.
    pub fn render_deny_sensitive_snippet(&self) -> String {
        r#"# Sensitive Files & Hidden Directory Protection
# Deny access to hidden files and directories (e.g. .git, .env) except .well-known
location ~ /\.(?!well-known) {
    deny all;
    access_log off;
    log_not_found off;
}

# Deny access to backup, sensitive configs, database dumps, and source files
location ~* (?:\.(?:bak|conf|dist|fla|in[ci]|log|psd|sh|sql|sw[op]|tpl)|~)$ {
    deny all;
    access_log off;
    log_not_found off;
}
"#
        .to_string()
    }

    /// Generates `snippets/fastcgi-params.conf`: Standard FastCGI parameters for PHP.
    pub fn render_fastcgi_params_snippet(&self) -> String {
        r#"# Standard Hardened FastCGI Parameters for PHP-FPM
fastcgi_param  QUERY_STRING       $query_string;
fastcgi_param  REQUEST_METHOD     $request_method;
fastcgi_param  CONTENT_TYPE       $content_type;
fastcgi_param  CONTENT_LENGTH     $content_length;

fastcgi_param  SCRIPT_NAME        $fastcgi_script_name;
fastcgi_param  REQUEST_URI        $request_uri;
fastcgi_param  DOCUMENT_URI       $document_uri;
fastcgi_param  DOCUMENT_ROOT      $document_root;
fastcgi_param  SERVER_PROTOCOL    $server_protocol;
fastcgi_param  REQUEST_SCHEME     $scheme;
fastcgi_param  HTTPS              $https if_not_empty;

fastcgi_param  GATEWAY_INTERFACE  CGI/1.1;
fastcgi_param  SERVER_SOFTWARE    nginx/$nginx_version;

fastcgi_param  REMOTE_ADDR        $remote_addr;
fastcgi_param  REMOTE_PORT        $remote_port;
fastcgi_param  SERVER_ADDR        $server_addr;
fastcgi_param  SERVER_PORT        $server_port;
fastcgi_param  SERVER_NAME        $server_name;

# PHP only, required if PHP was built with --enable-force-cgi-redirect
fastcgi_param  REDIRECT_STATUS    200;

# Script filename passed to PHP-FPM
fastcgi_param  SCRIPT_FILENAME    $document_root$fastcgi_script_name;
"#
        .to_string()
    }

    /// Generates logrotate configuration for virtual host site logs under `/var/log/panel/*/*/*.log`.
    pub fn render_logrotate_conf(&self) -> String {
        let pattern = self
            .log_dir
            .join("*/*/*.log")
            .to_string_lossy()
            .replace('\\', "/");
        format!(
            r#"# QonPanel Logrotate Configuration for Virtual Host Site Logs
{pattern} {{
    daily
    missingok
    rotate 14
    compress
    delaycompress
    notifempty
    create 0640 www-data adm
    sharedscripts
    postrotate
        [ -f /run/nginx.pid ] && kill -USR1 `cat /run/nginx.pid`
    endscript
}}
"#
        )
    }

    /// Creates all required directories and installs baseline configuration files.
    pub fn install_baseline(&self) -> Result<(), WebserverError> {
        // 1. Create directories
        fs::create_dir_all(&self.base_dir)?;
        fs::create_dir_all(self.conf_d_dir())?;
        fs::create_dir_all(self.snippets_dir())?;
        fs::create_dir_all(self.sites_available_dir())?;
        fs::create_dir_all(self.sites_enabled_dir())?;
        fs::create_dir_all(&self.log_dir)?;
        fs::create_dir_all(&self.acme_dir)?;
        fs::create_dir_all(&self.cache_dir)?;

        // 2. Write main nginx.conf
        write_file_atomic(&self.nginx_conf_path(), &self.render_nginx_conf())?;

        // 3. Write conf.d files
        write_file_atomic(
            &self.conf_d_dir().join("00-default.conf"),
            &self.render_default_catchall(),
        )?;
        write_file_atomic(
            &self.conf_d_dir().join("01-websocket.conf"),
            &self.render_websocket_conf(),
        )?;
        write_file_atomic(
            &self.conf_d_dir().join("10-panel.conf"),
            &self.render_panel_vhost(),
        )?;
        write_file_atomic(
            &self.conf_d_dir().join("20-fastcgi-cache.conf"),
            &self.render_fastcgi_cache_conf(),
        )?;

        // 4. Write snippets
        write_file_atomic(
            &self.snippets_dir().join("acme.conf"),
            &self.render_acme_snippet(),
        )?;
        write_file_atomic(
            &self.snippets_dir().join("security-headers.conf"),
            &self.render_security_headers_snippet(),
        )?;
        write_file_atomic(
            &self.snippets_dir().join("deny-sensitive.conf"),
            &self.render_deny_sensitive_snippet(),
        )?;
        write_file_atomic(
            &self.snippets_dir().join("fastcgi-params.conf"),
            &self.render_fastcgi_params_snippet(),
        )?;

        // 5. Write logrotate configuration
        write_file_atomic(
            &self.base_dir.join("logrotate.d/panel-sites"),
            &self.render_logrotate_conf(),
        )?;

        Ok(())
    }
}

/// Writes content to destination file via a temporary file to guarantee atomic replacement.
fn write_file_atomic(dest: &Path, content: &str) -> Result<(), WebserverError> {
    if let Some(parent) = dest.parent() {
        fs::create_dir_all(parent)?;
    }

    let temp_file = dest.with_extension("tmp");
    fs::write(&temp_file, content)?;
    fs::rename(&temp_file, dest)?;
    Ok(())
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used)]
mod tests {
    use super::*;
    use tempfile::TempDir;

    #[test]
    fn host_http_config_supplies_vhost_dependencies_without_duplicate_listeners() {
        let config = NginxBaselineConfig::default();
        let conf = config.render_host_http_conf();
        for required in [
            "log_format panel_json escape=json",
            "map $http_upgrade $connection_upgrade",
            "keys_zone=panel_php_cache:10m",
            "include /etc/panel/nginx/sites-enabled/*.conf;",
            "include /etc/panel/nginx/conf.d/tuning*.conf;",
        ] {
            assert!(conf.contains(required), "missing: {required}");
        }
        for standalone_only in [
            "listen ",
            "default_server",
            "http {",
            "user www-data",
            "conf.d/*.conf;",
        ] {
            assert!(
                !conf.contains(standalone_only),
                "unexpected: {standalone_only}"
            );
        }
    }

    #[test]
    fn test_render_logrotate_conf_format() {
        let config = NginxBaselineConfig::default();
        let logrotate = config.render_logrotate_conf();
        assert!(logrotate.contains("/var/log/panel/*/*/*.log"));
        assert!(logrotate.contains("daily"));
        assert!(logrotate.contains("rotate 14"));
        assert!(logrotate.contains("compress"));
        assert!(logrotate.contains("delaycompress"));
        assert!(logrotate.contains("create 0640 www-data adm"));
        assert!(logrotate.contains("postrotate"));
        assert!(logrotate.contains("kill -USR1"));
    }

    #[test]
    fn test_render_nginx_conf_structure_and_json_logging() {
        let config = NginxBaselineConfig::default();
        let conf = config.render_nginx_conf();

        assert!(conf.contains("worker_processes auto;"));
        assert!(conf.contains("worker_connections 4096;"));
        assert!(conf.contains("server_tokens off;"));
        assert!(conf.contains("log_format panel_json escape=json"));
        assert!(conf.contains("\"status\":$status"));
        assert!(conf.contains("\"time_local\":\"$time_iso8601\""));
        assert!(conf.contains("\"upstream_response_time\":\"$upstream_response_time\""));
        assert!(conf.contains("gzip on;"));
        assert!(conf.contains("include /etc/panel/nginx/conf.d/*.conf;"));
        assert!(conf.contains("include /etc/panel/nginx/sites-enabled/*.conf;"));
    }

    #[test]
    fn test_render_default_catchall_rejects_unknown_hosts() {
        let config = NginxBaselineConfig::default();
        let catchall = config.render_default_catchall();

        assert!(catchall.contains("listen 80 default_server;"));
        assert!(catchall.contains("listen 443 ssl default_server;"));
        assert!(catchall.contains("server_name _;"));
        assert!(catchall.contains("ssl_reject_handshake on;"));
        assert!(catchall.contains("return 444;"));
    }

    #[test]
    fn test_render_panel_vhost_proxies_to_api() {
        let config = NginxBaselineConfig::default();
        let vhost = config.render_panel_vhost();

        assert!(vhost.contains("listen 17890;"));
        assert!(vhost.contains("proxy_pass http://127.0.0.1:7700;"));
        assert!(vhost.contains("proxy_set_header Upgrade $http_upgrade;"));
        assert!(vhost.contains("proxy_set_header Connection \"upgrade\";"));
        assert!(vhost.contains("include /etc/panel/nginx/snippets/security-headers.conf;"));
    }

    #[test]
    fn panel_proxy_origin_contract_matches_installer_for_tunnel_and_custom_ports() {
        let config = NginxBaselineConfig {
            panel_listen_port: 19090,
            ..Default::default()
        };
        let generated = config.render_panel_vhost();
        let installer = include_str!("../../../templates/nginx/nusa-panel.conf")
            .replace("\r\n", "\n")
            .replace("@PANEL_PUBLIC_PORT@", "19090");
        for proxy in [&generated, &installer] {
            for directive in [
                "listen 19090;",
                "listen [::]:19090;",
                "map $remote_addr $qpanel_connector_visitor {\n    default \"\";\n    127.0.0.1 $http_cf_visitor;\n    ::1 $http_cf_visitor;\n}",
                "map $http_host $qpanel_public_authority {\n    default $http_host;\n    \"\" $host;\n}",
                "proxy_set_header Host $qpanel_public_authority;",
                "proxy_set_header X-Forwarded-Proto $scheme;",
                "proxy_set_header X-Qpanel-Cf-Visitor $qpanel_connector_visitor;",
                "proxy_set_header CF-Visitor \"\";",
                "proxy_set_header X-Forwarded-Host \"\";",
                "proxy_set_header Forwarded \"\";",
            ] {
                assert!(
                    proxy.contains(directive),
                    "Missing proxy contract: {directive}"
                );
            }
            assert!(!proxy.contains("proxy_set_header Host $host;"));
            assert!(!proxy.contains("proxy_set_header X-Forwarded-Proto $http_x_forwarded_proto;"));
        }
    }

    #[test]
    fn test_snippets_contain_security_rules() {
        let config = NginxBaselineConfig::default();

        let deny = config.render_deny_sensitive_snippet();
        assert!(deny.contains(r"location ~ /\.(?!well-known)"));
        assert!(deny.contains(
            r"location ~* (?:\.(?:bak|conf|dist|fla|in[ci]|log|psd|sh|sql|sw[op]|tpl)|~)$"
        ));
        assert!(deny.contains("deny all;"));

        let sec = config.render_security_headers_snippet();
        assert!(sec.contains("X-Frame-Options \"SAMEORIGIN\""));
        assert!(sec.contains("X-Content-Type-Options \"nosniff\""));
        assert!(sec.contains("Referrer-Policy \"strict-origin-when-cross-origin\""));

        let acme = config.render_acme_snippet();
        assert!(acme.contains("location ^~ /.well-known/acme-challenge/"));
        assert!(acme.contains("/var/lib/panel/acme"));

        let fastcgi = config.render_fastcgi_params_snippet();
        assert!(
            fastcgi
                .contains("fastcgi_param  SCRIPT_FILENAME    $document_root$fastcgi_script_name;")
        );
        assert!(fastcgi.contains("fastcgi_param  QUERY_STRING       $query_string;"));
    }

    #[test]
    fn test_install_baseline_creates_directory_structure_and_files() {
        let temp = TempDir::new().unwrap();
        let config = NginxBaselineConfig::new(temp.path().join("nginx"));

        assert!(config.install_baseline().is_ok());

        assert!(config.nginx_conf_path().exists());
        assert!(config.conf_d_dir().join("00-default.conf").exists());
        assert!(config.conf_d_dir().join("10-panel.conf").exists());
        assert!(config.snippets_dir().join("acme.conf").exists());
        assert!(config.snippets_dir().join("security-headers.conf").exists());
        assert!(config.snippets_dir().join("deny-sensitive.conf").exists());
        assert!(config.snippets_dir().join("fastcgi-params.conf").exists());
        assert!(config.sites_available_dir().exists());
        assert!(config.sites_enabled_dir().exists());
        assert!(config.log_dir.exists());
        assert!(config.acme_dir.exists());
        assert!(config.cache_dir.exists());
        assert!(config.conf_d_dir().join("20-fastcgi-cache.conf").exists());

        // Validate contents written match renderer
        let written_catchall =
            fs::read_to_string(config.conf_d_dir().join("00-default.conf")).unwrap();
        assert!(written_catchall.contains("return 444;"));

        let written_cache =
            fs::read_to_string(config.conf_d_dir().join("20-fastcgi-cache.conf")).unwrap();
        assert!(written_cache.contains("keys_zone=panel_php_cache:10m"));
    }
}
