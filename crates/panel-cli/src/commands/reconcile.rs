use panel_core::reconcile::{DriftItem, DriftType, ReconcileReport, format_reconcile_report_cli};
use panel_db::pool::DbPool;
use panel_db::repositories::domain_repo::SqliteDomainRepository;
use panel_db::repositories::job_repo::SqliteJobRepository;
use panel_db::repositories::site_repo::SqliteSiteRepository;
use panel_db::repositories::user_repo::SqliteUserRepository;
use panel_proto::ReconcileSiteInputDto;
#[cfg(unix)]
use panel_proto::{RequestPayload, RpcRequest, RpcStream, SystemReconcileRequest};
use std::error::Error;
use std::path::Path;
use std::time::{SystemTime, UNIX_EPOCH};
use tracing::info;

#[derive(Debug, Clone, Default)]
pub struct ReconcileCliOptions {
    pub dry_run: bool,
    pub json: bool,
}

pub async fn run_reconcile(
    options: &ReconcileCliOptions,
    pool: &DbPool,
    _db_path: &str,
) -> Result<ReconcileReport, Box<dyn Error>> {
    let timestamp = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs();

    let site_repo = SqliteSiteRepository::new(pool.clone());
    let domain_repo = SqliteDomainRepository::new(pool.clone());
    let user_repo = SqliteUserRepository::new(pool.clone());
    let operations = panel_db::operations::for_maintenance(pool).await?;
    let job_repo = SqliteJobRepository::new(operations.clone());

    let sites = site_repo.list_all().await?;
    let users = user_repo.list_all().await?;

    let mut drifts = Vec::new();
    let mut desired_sites_dto = Vec::new();

    // 1. Inspect Sites & Nginx Vhosts & Docroots
    for site in &sites {
        let owner = users.iter().find(|u| u.id == site.user_id);
        let username = owner
            .and_then(|u| u.linux_username.as_deref())
            .unwrap_or("p_unknown");
        let uid = owner.and_then(|u| u.linux_uid).unwrap_or(1000) as u32;

        let primary_domain = domain_repo
            .find_primary_by_site_id(site.id)
            .await?
            .map(|d| d.name)
            .unwrap_or_else(|| format!("site-{}", site.id));

        let vhost_conf_path =
            Path::new("/etc/panel/nginx/sites-available").join(format!("{}.conf", site.id));
        let docroot_path = Path::new(&site.docroot);

        // Check missing Nginx config
        if !vhost_conf_path.exists() {
            drifts.push(DriftItem {
                id: format!("site_{}_vhost_missing", site.id),
                drift_type: DriftType::MissingNginxConfig,
                resource_type: "nginx_vhost".to_string(),
                resource_id: format!("{}:{}", site.id, primary_domain),
                description: format!(
                    "Berkas konfigurasi Nginx vhost tidak ada di disk: {}",
                    vhost_conf_path.display()
                ),
                desired_state: format!("Berkas {} ada dan aktif", vhost_conf_path.display()),
                actual_state: "Berkas tidak ditemukan".to_string(),
                remediation_action: "Buat ulang berkas konfigurasi Nginx dan aktifkan symlink"
                    .to_string(),
            });
        }

        // Check missing Docroot directory
        if !docroot_path.exists() {
            drifts.push(DriftItem {
                id: format!("site_{}_docroot_missing", site.id),
                drift_type: DriftType::MissingDocrootDirectory,
                resource_type: "docroot".to_string(),
                resource_id: format!("{}:{}", site.id, site.docroot),
                description: format!(
                    "Direktori docroot situs belum ada di {}",
                    docroot_path.display()
                ),
                desired_state: format!("Direktori {} ada (UID: {})", site.docroot, uid),
                actual_state: "Direktori tidak ditemukan".to_string(),
                remediation_action: "Buat direktori docroot dengan izin kepemilikan tenant"
                    .to_string(),
            });
        }

        desired_sites_dto.push(ReconcileSiteInputDto {
            site_id: site.id,
            domain: primary_domain,
            username: username.to_string(),
            uid,
            kind: site.kind.clone(),
            docroot: site.docroot.clone(),
            config_content: format!(
                "# Auto-generated by Qinpanel Reconciler\nserver {{\n    listen 80;\n    server_name {};\n    root {};\n}}\n",
                site.docroot, site.docroot
            ),
            is_active: site.status == "active",
        });
    }

    // 2. Inspect stuck jobs
    let stuck_count: i64 =
        sqlx::query_scalar("SELECT COUNT(*) FROM jobs WHERE status = 'running';")
            .fetch_one(&operations)
            .await
            .unwrap_or(0);

    if stuck_count > 0 {
        drifts.push(DriftItem {
            id: "stuck_running_jobs".to_string(),
            drift_type: DriftType::InterruptedJobStuck,
            resource_type: "job_queue".to_string(),
            resource_id: format!("stuck_jobs_count_{}", stuck_count),
            description: format!(
                "Ditemukan {} antrean pekerjaan tertahan dalam status 'running'",
                stuck_count
            ),
            desired_state: "Tidak ada pekerjaan macet dalam status 'running'".to_string(),
            actual_state: format!("{} pekerjaan terhenti", stuck_count),
            remediation_action: "Tandai gagal pekerjaan yang terinterupsi saat restart".to_string(),
        });
    }

    // If not dry-run, execute reconciliation actions!
    if !options.dry_run {
        // Recover interrupted jobs
        if stuck_count > 0 {
            let recovered = job_repo.recover_interrupted_jobs().await?;
            info!("Memulihkan {} pekerjaan yang macet", recovered);
        }

        // Send reconcile IPC request to Agent if socket is available
        #[cfg(unix)]
        let socket_path = Path::new("/run/panel/agent.sock");
        #[cfg(unix)]
        if socket_path.exists()
            && let Ok(stream) = tokio::net::UnixStream::connect(socket_path).await
        {
            let mut rpc = RpcStream::new(stream);
            let rec_req = RpcRequest::new(
                "cli-rec-1",
                RequestPayload::SystemReconcile(SystemReconcileRequest {
                    dry_run: false,
                    desired_sites: desired_sites_dto,
                    desired_nftables_ports: vec![],
                }),
            );
            let _ = rpc.send_request(&rec_req).await;
        }
    }

    let report = ReconcileReport::new(timestamp, sites.len(), drifts);

    if options.json {
        let json_str = serde_json::to_string_pretty(&report)?;
        println!("{}", json_str);
    } else {
        let cli_out = format_reconcile_report_cli(&report, true);
        println!("{}", cli_out);
    }

    Ok(report)
}
